import React, { useRef, useEffect } from 'react';
import { useInView, animate } from 'motion/react';

export const AnimatedNumber = ({ value }: { value: number }) => {
    const ref = useRef<HTMLSpanElement>(null);
    const isInView = useInView(ref, { once: true });

    useEffect(() => {
        if (!isInView || !ref.current) return;

        // ⚡ BOLT OPTIMIZATION:
        // Use Framer Motion's `animate` with direct DOM manipulation (`textContent`).
        // This eliminates unnecessary React re-renders that would occur with state-based (e.g. `useState`) animations,
        // making the counter animation significantly smoother and less resource-intensive.
        const controls = animate(0, value, {
            duration: 2,
            onUpdate(v) {
                if (ref.current) {
                    ref.current.textContent = Math.floor(v).toString();
                }
            },
            onComplete() {
                if (ref.current) {
                    ref.current.textContent = value.toString();
                }
            }
        });

        return () => controls.stop();
    }, [isInView, value]);

    return <span ref={ref}>0</span>;
};
